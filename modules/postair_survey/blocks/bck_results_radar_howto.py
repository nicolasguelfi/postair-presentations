"""How to read a posture radar — the example chart and the four posture codes.

Opens the results sequence, immediately before the room sees its own numbers.
The radar shown is an EXAMPLE, generated by ``_project/tools/make_radar.py``
and labelled as such on the slide: the published archetype coordinates live
in the sumvadis demo, and putting invented values under a real archetype's
name would be a fabrication.

SPEAKER NOTES:
Four minutes, and they buy you the next twenty. Three things, in order.
First: the centre is not zero-opinion — it is one of the two poles, so a
small shape does not mean a small personality. Second: distance from the
centre is a position, not a score; nobody wins a radar. Third: the four
codes, and above all ambivalent — it means someone agrees with BOTH poles,
which is the most interesting result the instrument produces and the one
people misread as indecision. Say that last part slowly.
"""
